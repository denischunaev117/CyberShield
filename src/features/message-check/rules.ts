export type RiskRule = {
  id: string;
  category: string;
  severity: "low" | "medium" | "high";
  reason: string;
  advice: string;
  examples: string[];
  version: number;
  skillId: SkillId;
  sourceIds: string[];
  test: (text: string) => boolean;
};
type Detector = RegExp | ((text: string) => boolean);
const has = (t: string, ...patterns: RegExp[]) =>
  patterns.every((p) => matches(p, t));
const request = (p: RegExp) => (t: string) => affirmativeRequest(t, p);
const secret =
  /(?:пришл[а-я]*|перешл[а-я]*|присл[а-я]*|ски[а-я]*|отправ[а-я]*|сообщ[а-я]*|назов[а-я]*|продикт[а-я]*|переда[а-я]*|напиш[а-я]*|покаж[а-я]*|дайте|дай|нужен|нужны|требуется|вышл[а-я]*)[^.!?;]{0,100}(?:код|парол|пин|pin|cvv|cvc|цифр[а-я]* из (?:смс|sms))/;
function requestsSecret(t: string) {
  const reverse = t
    .split(/[.!?;]/)
    .some(
      (clause) =>
        /код|парол|пин/.test(clause) &&
        affirmativeRequest(
          clause,
          /(?:пришл[а-я]*|перешл[а-я]*|ски[а-я]*|напиш[а-я]*|сообщ[а-я]*|продикт[а-я]*|назов[а-я]*|жду|ожидаем|отправ[а-я]*|переда[а-я]*)/,
        ),
    );
  return (
    affirmativeRequest(t, secret) ||
    reverse ||
    (/код|парол|пин/.test(t) &&
      affirmativeRequest(
        t,
        /(?:пришл|ски[а-я]*|отправ|переда|напиш|продикт)[а-я]*[^.!?;]{0,20}(?:его|их|эти цифры)/,
      )) ||
    affirmativeRequest(
      t,
      /(?:введ[а-я]*|укаж[а-я]*)[^.!?;]{0,45}(?:парол|код)[^.!?;]{0,55}(?:ссылк|форм|сайт|анкет)/,
    )
  );
}

const rule = (
  id: string,
  category: string,
  severity: RiskRule["severity"],
  reason: string,
  advice: string,
  examples: string[],
  skillId: SkillId,
  detector: Detector,
  sourceIds: string[] = ["mvd"],
): RiskRule => ({
  id,
  category,
  severity,
  reason,
  advice,
  examples,
  skillId,
  sourceIds,
  version: 2,
  test: (raw) => {
    const text = normalizeMessage(raw);
    return (
      (typeof detector === "function"
        ? detector(text)
        : matches(detector, text)) || recognizesAdditionalLanguage(id, text)
    );
  },
});
