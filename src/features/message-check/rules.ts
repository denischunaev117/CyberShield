export type RiskRule = {
  id: string;
  category: string;
  severity: "low" | "medium" | "high";
  reason: string;
  advice: string;
  examples: string[];
  version: number;
  skillId: SkillId;
  sourceIds: string[];
  test: (text: string) => boolean;
};
function requestsSecret(text: string) {
  const pattern =
    /(?:сообщ\w*|сообщ[а-яё]*|пришл[а-яё]*|продикт[а-яё]*|отправ[а-яё]*|переда[а-яё]*|назов[а-яё]*)[\s\S]{0,45}(?:код|парол|пин|pin)/gi;
  for (const match of text.matchAll(pattern)) {
    const prefix = text.slice(Math.max(0, match.index! - 16), match.index);
    if (
      !/(?:не|нельзя)\s*$/i.test(prefix) ||
      /кроме|только (?:нам|нашему)/i.test(
        match[0] +
          text.slice(
            match.index! + match[0].length,
            match.index! + match[0].length + 45,
          ),
      )
    )
      return true;
  }
  return /(?:введите|укажите)[\s\S]{0,35}(?:парол|код)[\s\S]{0,35}(?:ссылк|форм|сайт)/i.test(
    text,
  );
}
