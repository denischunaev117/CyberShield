// The excerpt is derived from current UI state only, never added to RiskAnalysis.
export function ruleExcerpt(text: string, r: RiskRule): string {
  const parts = text.split(/(?<=[.!?;])\s+|\n+/);
  for (const span of [1, 2, 3]) {
    for (let i = 0; i < parts.length; i++) {
      const excerpt = parts
        .slice(i, i + span)
        .join(" ")
        .trim();
      if (r.test(excerpt)) return excerpt;
    }
  }
  return text.trim();
}
