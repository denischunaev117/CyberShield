const doc = (title: string, rows: [string, string][]): Evidence => ({
  kind: "document",
  title,
  rows: rows.map(([label, value]) => ({ label, value })),
});
function voice(s: Scenario): Scenario {
  return {
    ...s,
    nodes: Object.fromEntries(
      Object.entries(s.nodes).map(([id, node]) => [
        id,
        {
          ...node,
          ...(node.speaker !== "narrator"
            ? { audio: `/audio/${s.id}-${id}.mp3` }
            : {}),
        },
      ]),
    ),
  };
}
