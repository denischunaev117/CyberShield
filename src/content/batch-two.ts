import type { Choice, Scenario, Scene, Ending } from "../engine";
type Option = [
  text: string,
  next: string,
  assessment: Choice["assessment"],
  explanation: string,
];
const node = (
  message: string,
  options: Option[],
  speaker?: "narrator",
): Scene => ({
  message,
  speaker,
  choices: options.map(([text, next, assessment, explanation], i) => ({
    id: `answer-${i + 1}`,
    text,
    next,
    assessment,
    explanation,
  })),
});
const end = (
  title: string,
  message: string,
  outcome: Ending["outcome"],
): Ending => ({ title, message, outcome });
type Story = Omit<Scenario, "avatar" | "duration" | "difficulty" | "start">;
