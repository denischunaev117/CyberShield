import type { SkillId } from "./skills";
export type LessonQuestion = {
  id: string;
  skillId: SkillId;
  text: string;
  options: {
    id: string;
    text: string;
    points: 0 | 1 | 2;
    explanation: string;
  }[];
};
export type Lesson = {
  id: string;
  revision: 1;
  title: string;
  audience: string;
  duration: string;
  outcomes: string[];
  schedule: { title: string; minutes: string; activity: string }[];
  scenarioIds: string[];
  discussion: { question: string; answer: string }[];
  quiz: LessonQuestion[];
};
const q = (
  id: string,
  skillId: SkillId,
  text: string,
  options: [string, 0 | 1 | 2, string][],
): LessonQuestion => ({
  id,
  skillId,
  text,
  options: options.map(([text, points, explanation], i) => ({
    id: `o${i + 1}`,
    text,
    points,
    explanation,
  })),
});
